import { test, expect } from '@playwright/test';
import path from 'node:path';

const base = process.env.KAGERO_E2E_URL!;
const evidence = path.resolve('.artifacts/kagero-runtime-1.1/e2e');

test('D1 mutations, partial reload, history and CSRF rejection', async ({ page, context }) => {
  await page.goto(base);
  await expect(page).toHaveTitle('Kagero D1 Todo');
  const initialCookie = (await context.cookies()).find(c => c.name === 'XSRF-TOKEN');
  expect(initialCookie).toBeTruthy();
  const inertiaGet = await context.request.get(base, { headers: { 'X-Inertia': 'true', 'X-Inertia-Version': 'kagero-1' } });
  expect(inertiaGet.headers()['x-inertia']).toBe('true');
  expect((await inertiaGet.json()).component).toBe('Todos/Index');
  await page.locator('#title').fill('日本語の買い物');
  const postResponse = page.waitForResponse(r => r.url().endsWith('/todos') && r.request().method() === 'POST');
  await page.getByRole('button', { name: '追加' }).click();
  const posted = await postResponse;
  expect(posted.headers()['x-inertia']).toBe('true');
  expect((await posted.json()).component).toBe('Todos/Index');
  await expect(page.getByText('日本語の買い物')).toBeVisible();
  await page.screenshot({ path: `${evidence}/add.png` });
  await page.getByRole('button', { name: '追加' }).click();
  await expect(page.getByText('タイトルは必須です')).toBeVisible();
  await page.screenshot({ path: `${evidence}/validation.png` });
  const row = page.locator('li').filter({ hasText: '日本語の買い物' });
  await row.getByRole('button', { name: '完了' }).click();
  await expect(row.getByText('Done')).toBeVisible();
  await page.screenshot({ path: `${evidence}/done.png` });
  await row.getByRole('button', { name: '削除' }).click();
  await expect(row).toHaveCount(0);
  await page.screenshot({ path: `${evidence}/delete.png` });
  const before = Number(await page.locator('[data-testid=stats] .stat strong').first().innerText());
  const existing = await page.getByText('別経路の追加').count();
  const cookie = (await context.cookies()).find(c => c.name === 'XSRF-TOKEN')!;
  const other = await context.request.post(`${base}/todos`, { headers: { 'X-XSRF-TOKEN': cookie.value, 'X-Inertia': 'true', 'X-Inertia-Version': 'kagero-1' }, form: { title: '別経路の追加' } });
  expect(other.status()).toBe(200);
  await page.getByRole('button', { name: 'Refresh stats' }).click();
  await expect(page.getByText('別経路の追加')).toHaveCount(existing + 1);
  await expect(page.locator('[data-testid=stats] .stat strong').first()).toHaveText(String(before + 1));
  await page.screenshot({ path: `${evidence}/partial.png` });
  const length = await page.evaluate(() => history.length);
  await page.getByRole('link', { name: '完了済み' }).click();
  await expect(page).toHaveTitle('完了済み TODO');
  await page.screenshot({ path: `${evidence}/second-page.png` });
  await page.goBack();
  await expect(page).toHaveTitle('Kagero D1 Todo');
  await expect(page.getByText('別経路の追加')).toHaveCount(existing + 1);
  expect(await page.evaluate(() => history.length)).toBe(length + 1);
  expect(await page.evaluate(() => JSON.parse(document.querySelector('[data-kagero-root]')!.getAttribute('data-page')!).url)).toBe('/');
  await page.screenshot({ path: `${evidence}/back.png` });
  const count = Number(await page.locator('[data-testid=stats] .stat strong').first().innerText());
  const rejected = await context.request.post(`${base}/todos`, { form: { title: '拒否される' } });
  expect(rejected.status()).toBe(403);
  await page.reload();
  await expect(page.locator('[data-testid=stats] .stat strong').first()).toHaveText(String(count));
  await context.clearCookies();
  await page.locator('#title').fill('消えない入力');
  await page.getByRole('button', { name: '追加' }).click();
  await expect(page.getByRole('alert')).toContainText('操作に失敗');
  await expect(page.locator('#title')).toHaveValue('消えない入力');
  await page.screenshot({ path: `${evidence}/csrf-error.png` });
});

test('a valid page without X-Inertia is applied', async ({ page, context }) => {
  await page.goto(base);
  await expect(page).toHaveTitle('Kagero D1 Todo');
  await page.getByRole('link', { name: '完了済み' }).click();
  await expect(page).toHaveTitle('完了済み TODO');
  await context.clearCookies();
  const responsePromise = page.waitForResponse(r => r.request().headers()['x-inertia'] === 'true' && r.url() === `${base}/`);
  await page.evaluate(() => (window as any).Kagero.visit('/'));
  const response = await responsePromise;
  expect(response.headers()['x-inertia']).toBeUndefined();
  expect((await response.json()).component).toBe('Todos/Index');
  await expect(page).toHaveTitle('Kagero D1 Todo');
  await expect(page.getByRole('heading', { name: 'Ruby-way Inertia experience on Workers' })).toBeVisible();
  await expect(page.locator('#kagero-visit-error')).toHaveCount(0);
  await page.screenshot({ path: `${evidence}/missing-inertia-header.png` });
  await page.locator('#title').fill('保持する');
  const assetResponse = page.waitForResponse(r => r.url().endsWith('/assets/kagero.js'));
  await page.evaluate(() => (window as any).Kagero.visit('/assets/kagero.js'));
  expect((await assetResponse).status()).toBe(404);
  await expect(page.locator('#kagero-visit-error')).toBeVisible();
  await expect(page.locator('#title')).toHaveValue('保持する');
  await page.screenshot({ path: `${evidence}/not-found-error.png` });
});
